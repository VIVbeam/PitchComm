// Generates the shared protocol fixtures in dev/protocol/.
// Run from the repository root: node gui/test/generate_fixtures.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { command } from '../core.js';

const catalog = JSON.parse(readFileSync(new URL('../catalog.json', import.meta.url), 'utf8'));

export const COUNTS = Object.freeze({
  rows: catalog.rows.length,
  cols: catalog.cols.length,
  maxPitch: catalog.pitchFlow.maxCode,
  pitchFlow: catalog.pitchFlow,
  maxPlay: catalog.plays.length,
  unitCount: catalog.units.length + 1,
});

export const FIXED_SESSION = Object.freeze({
  client: '1a2b3c4d',
  boot: '0011223344556677',
  dictionary: catalog.dictionary,
});

export const SESSION_CLOCKS = Object.freeze({
  base: 0x00001000,
  wrapToZero: 0xfffffa24,
  wrapSmall: 0xffffffff,
});

const UNIT_ORDER = ['Coach', ...catalog.units.map((unit, index) => `${index + 1} ${unit.label}`)].join(', ');

