function frameLine(frame) {
  return `@PC ${JSON.stringify(frame)}\n`;
}

export function buildStateFramesText() {
  const lines = [...stateSamples(), ...resultSamples()].map(frameLine).join('');
  return FRAME_HEADER + lines;
}

function main() {
  const outDir = fileURLToPath(new URL('../../dev/protocol/', import.meta.url));
  mkdirSync(outDir, { recursive: true });
  writeFileSync(path.join(outDir, 'gui_commands.txt'), buildGuiCommandsText());
  writeFileSync(path.join(outDir, 'state_frames.txt'), buildStateFramesText());
  const calls = commandRecords().filter(record => record.kind !== 'gui').length;
  console.log(`Wrote dev/protocol/gui_commands.txt (${calls} commands plus the gui handshake)`);
  console.log(`Wrote dev/protocol/state_frames.txt (${stateSamples().length} states, ${resultSamples().length} results)`);
}

const invokedDirectly = process.argv[1]
  ? path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
  : false;
if (invokedDirectly) main();
