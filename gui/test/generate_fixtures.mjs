function firstPitchSample() {
  return { type: catalog.pitches[0].key, row: catalog.rows[0].key, col: catalog.cols[0].key };
}

function lastPitchSample() {
  return {
    type: catalog.pitches[catalog.pitches.length - 1].key,
    row: catalog.rows[catalog.rows.length - 1].key,
    col: catalog.cols[catalog.cols.length - 1].key,
  };
}

export function pitchSamples() {
  // One sample per pitch type, walking valid row and col positions so every
  // call code is distinct and inside the configured grid.
  return catalog.pitches.map((pitch, index) => ({
    type: pitch.key,
    row: (index % COUNTS.rows) + 1,
    col: Math.floor(index / COUNTS.rows) % COUNTS.cols + 1,
  }));
}

function session(clock) {
  return { ...FIXED_SESSION, clock };
}

export function commandRecords() {
  const records = [{ kind: 'gui', line: `gui ${FIXED_SESSION.client}\n` }];
  let id = 1;
  for (const sample of pitchSamples()) {
    records.push({
      kind: 'pitch',
      id,
      clock: SESSION_CLOCKS.base,
      ...sample,
      line: command(id, 1, sample.type, sample.row, sample.col, session(SESSION_CLOCKS.base), COUNTS),
    });
    id += 1;
  }
  for (const play of [1, COUNTS.maxPlay]) {
    records.push({
      kind: 'play',
      id,
      play,
      clock: SESSION_CLOCKS.base,
      line: command(id, 2, play, 0, 0, session(SESSION_CLOCKS.base), COUNTS),
    });
    id += 1;
  }
  const first = firstPitchSample();
  records.push({
    kind: 'pitch-wrap',
    id,
    ...first,
    clock: SESSION_CLOCKS.wrapToZero,
    line: command(id, 1, first.type, first.row, first.col, session(SESSION_CLOCKS.wrapToZero), COUNTS),
  });
  id += 1;
  const last = lastPitchSample();
  records.push({
    kind: 'pitch-wrap',
    id,
    ...last,
    clock: SESSION_CLOCKS.wrapSmall,
    line: command(id, 1, last.type, last.row, last.col, session(SESSION_CLOCKS.wrapSmall), COUNTS),
  });
  id += 1;
  for (const sample of pitchSamples()) {
    for (const stage of ['type', 'placement']) {
      const clock=stage==='type' ? SESSION_CLOCKS.wrapToZero : SESSION_CLOCKS.wrapSmall;
      records.push({kind:stage,id,clock,...sample,
        line:command(id,1,sample.type,sample.row,sample.col,session(clock),COUNTS,stage)});
      ++id;
    }
  }
  return records;
}

export function buildGuiCommandsText() {
  return COMMAND_HEADER + commandRecords().map(record => record.line).join('');
}

