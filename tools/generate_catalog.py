"""Generate matching firmware and laptop dictionaries (standard library only)."""
import json
import os
import secrets
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEIGHTS = ('UP', 'MIDDLE', 'DOWN')
SIDES = ('INSIDE', 'MIDDLE', 'AWAY')


def atomic_text(path,contents):
    temporary=None
    try:
        with tempfile.NamedTemporaryFile(mode='w',encoding='utf-8',newline='\n',
                                         dir=path.parent,prefix='.'+path.name+'.',suffix='.tmp',delete=False) as output:
            temporary=Path(output.name)
            output.write(contents); output.flush(); os.fsync(output.fileno())
        os.replace(temporary,path)
    finally:
        if temporary is not None: temporary.unlink(missing_ok=True)

def pitch_code(pitch, height, side):
    if not 1 <= pitch <= 9 or not 1 <= height <= 3 or not 1 <= side <= 3:
        raise ValueError('Pitch 1..9, height 1..3, side 1..3 required')
    return (pitch - 1) * 9 + (height - 1) * 3 + side

def load(root=None):
    root = ROOT if root is None else Path(root)
    data = json.loads((root / 'config/calls.json').read_text(encoding='utf-8'))
    for group in ('pitches', 'plays'):
        items = data[group]
        if not isinstance(items,list) or len(items) != 9 or any(not isinstance(x,dict) or type(x.get('key')) is not int for x in items) or sorted(x['key'] for x in items) != list(range(1, 10)):
            raise ValueError(f'{group} must define keys 1 through 9 exactly once')
        fields = ('label', 'speech') if group == 'pitches' else ('label', 'shortstop', 'centerfield')
        for item in items:
            for field in fields:
                text = item[field]
                if not isinstance(text, str) or not text or any(not 32 <= ord(c) <= 126 for c in text):
                    raise ValueError(f'{group}: {field} must be nonempty printable ASCII')
                if not text.strip() or text!=text.strip():
                    raise ValueError(f'{group}: {field} must contain text without leading or trailing spaces')
                limit = 10 if group == 'pitches' and field == 'label' else 12
                if field != 'speech' and (len(text) > limit or any(len(w) > 10 for w in text.split())):
                    raise ValueError(f'{group}: display text is too long')
                if field == 'speech' and len(text) > 80:
                    raise ValueError('Speech must be at most 80 characters')
    canonical = json.dumps({'schema': 2, 'calls': data, 'heights': HEIGHTS, 'sides': SIDES},
                           sort_keys=True, separators=(',', ':')).encode()
    value = 2166136261
    for byte in canonical:
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return data, value

def clips(data):
    return [(f'p{x["key"]:02d}.wav', x['speech']) for x in sorted(data['pitches'], key=lambda x: x['key'])] + \
           [(f'h{i}.wav', text.title()) for i, text in enumerate(HEIGHTS, 1)] + \
           [(f's{i}.wav', text.title()) for i, text in enumerate(SIDES, 1)]

def rendered(root=None):
    """Return both generated files without changing the project."""
    data, version = load(root)
    lines = ['// Generated by tools/generate_catalog.py; edit config/calls.json instead.',
             '#pragma once', '#include "protocol.h"', 'namespace pc {',
             f'constexpr uint32_t kDictionary = 0x{version:08x}u;',
             'constexpr uint16_t pitchCode(unsigned type, unsigned height, unsigned side) {',
             '  return type>=1 && type<=9 && height>=1 && height<=3 && side>=1 && side<=3 ? uint16_t((type-1)*9+(height-1)*3+side) : 0;', '}',
             'struct Call { Category category; uint16_t code; const char* label; const char* ss; const char* cf; const char* audio[3]; };',
             'inline constexpr const char* kAudioClips[] = {']
    lines += [f'  "/audio/{name}",' for name, _ in clips(data)]
    lines += ['};', 'inline constexpr const char* kPitchNames[] = {']
    lines += [f'  {json.dumps(p["label"])},' for p in sorted(data['pitches'], key=lambda x: x['key'])]
    lines += ['};', 'inline constexpr Call kCalls[] = {']
    for pitch in sorted(data['pitches'], key=lambda x: x['key']):
        for height, htext in enumerate(HEIGHTS, 1):
            for side, stext in enumerate(SIDES, 1):
                label = f'{pitch["label"]} {htext} {stext}'
                fields = ', '.join(json.dumps(label) for _ in range(3))
                audio = ', '.join(json.dumps(f'/audio/{name}') for name in (f'p{pitch["key"]:02d}.wav', f'h{height}.wav', f's{side}.wav'))
                lines.append(f'  {{Category::Pitch, {pitch_code(pitch["key"], height, side)}, {fields}, {{{audio}}}}},')
    for item in sorted(data['plays'], key=lambda x: x['key']):
        fields = ', '.join(json.dumps(item[x]) for x in ('label', 'shortstop', 'centerfield'))
        lines.append(f'  {{Category::Play, {item["key"]}, {fields}, {{"", "", ""}}}},')
    lines += ['};', 'inline const Call* findCall(Category cat, uint16_t code) {',
              '  for (const auto& c:kCalls) if (c.category==cat && c.code==code) return &c;', '  return nullptr;', '}',
              'inline const char* labelFor(const Call& c, Role role) {',
              '  return role==Role::Shortstop ? c.ss : role==Role::Centerfield ? c.cf : c.label;', '}',
              'constexpr uint8_t recipients(Category category) {',
              '  return roleMask(Role::Coach) | (category==Category::Pitch ? (roleMask(Role::Catcher)|roleMask(Role::Pitcher)) : (roleMask(Role::Shortstop)|roleMask(Role::Centerfield)));',
              '}', '} // namespace pc', '']
    return version, {
        'firmware/include/pc/catalog.h': '\n'.join(lines),
        'gui/catalog.json': json.dumps({'dictionary': f'{version:08x}', **data,
                                       'heights': HEIGHTS, 'sides': SIDES}, indent=2) + '\n',
    }

def generate():
    # Vocabulary belongs to the same setup transaction as firmware keys and
    # recordings. Hold exclusion across rendering and both generated writes,
    # so an upload cannot observe a dictionary changed halfway through a build.
    build=ROOT/'build'
    build.mkdir(exist_ok=True)
    lock=build/'validation.lock'
    owner=f'CATALOG GENERATION PID {os.getpid()} TOKEN {secrets.token_hex(16)}\n'.encode('ascii')
    try:
        handle=lock.open('xb')
    except FileExistsError as error:
        raise ValueError('Configuration is already locked. Finish active upload, validation, provisioning '
                         'or audio/catalog generation before regenerating vocabulary. After an '
                         'interruption, verify the owning process stopped before clearing '
                         'build/validation.lock; then rerun generation and preflight.') from error
    identity=os.fstat(handle.fileno())
    published=False
    try:
        with handle:
            handle.write(owner)
            handle.flush()
            os.fsync(handle.fileno())
        published=True
        version, files = rendered()
        for name, contents in files.items():
            target = ROOT / name
            target.parent.mkdir(parents=True, exist_ok=True)
            atomic_text(target,contents)
        print(f'Dictionary {version:08x}: 81 complete pitches, 9 plays, 15 audio clips')
    finally:
        # Never clear another operation's replacement/interrupted lock.
        try:
            current=lock.stat()
            same_creation=(current.st_dev,current.st_ino)==(identity.st_dev,identity.st_ino)
            if lock.read_bytes()==owner or (not published and same_creation):
                lock.unlink()
        except FileNotFoundError:
            pass

if __name__ == '__main__':
    generate()
